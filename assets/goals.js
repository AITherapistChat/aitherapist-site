/* Цели Яндекс.Метрики для контентных страниц (блог, тесты, подходы, юр-страницы).
   На главной тот же слушатель живёт инлайном в index.html — сюда её НЕ подключаем,
   иначе клик посчитается дважды.

   Зачем файл появился (31.08.2026): цель rustore_click стояла только на index.html,
   а на 35 контентных страницах ссылок на RuStore не было вовсе. Под рекламу в Директе
   это значило, что весь дешёвый информационный трафик некуда конвертировать —
   оптимизировать кампанию по цели было физически не на чем.

   Копий не заводить: в блоге мы уже получили 18 разошедшихся копий одного скрипта. */
(function () {
  "use strict";

  /* Делегированный слушатель: ловит и кнопки, которые появятся в DOM позже.
     Ссылки на другие наши приложения (Метакарты, Fate AI) намеренно не попадают —
     у них другие com.*-адреса, иначе число установок AI Therapist было бы завышено. */
  document.addEventListener("click", function (e) {
    var a = e.target.closest && e.target.closest('a[href*="com.example.aitherapist"]');
    if (!a) return;
    /* data-goal — чтобы в отчёте было видно, какой блок сработал:
       cta — кнопка под статьёй, nav — бейдж в шапке, text — ссылка в тексте. */
    var where = a.getAttribute("data-goal") || "text";
    if (window.ym && window.__metrikaId) {
      try { ym(window.__metrikaId, "reachGoal", "rustore_click", { button: where }); } catch (_) {}
    }
  }, true);
})();
