def check():
    """Все поля, которые Директ обрежет молча."""
    bad = []
    for cname, groups, _ in CAMPAIGNS:
        for g in groups:
            for field in ('h1', 'h2', 'text'):
                n = len(g[field])
                if n > LIM[field]:
                    bad.append('%s / %s: %s = %d симв. (лимит %d) — «%s»'
                               % (cname, g['name'], field, n, LIM[field], g[field]))
    for t, _u, d in SITELINKS:
        if len(t) > LIM['sl_title']:
            bad.append('быстрая ссылка «%s»: заголовок %d (лимит %d)'
                       % (t, len(t), LIM['sl_title']))
        if len(d) > LIM['sl_desc']:
            bad.append('быстрая ссылка «%s»: описание %d (лимит %d)'
                       % (t, len(d), LIM['sl_desc']))
    for c in CALLOUTS:
        if len(c) > LIM['callout']:
            bad.append('уточнение «%s»: %d (лимит %d)' % (c, len(c), LIM['callout']))
    return bad


def main():
    bad = check()
    if bad:
        print('ЛИМИТЫ ПРЕВЫШЕНЫ (%d):' % len(bad))
        for b in bad:
            print('  * ' + b)
        return 1
    print('Лимиты Директа: всё в пределах.\n')
    if '--check' in sys.argv:
        return 0

    week = 0
    for cname, groups, budget in CAMPAIGNS:
        kw_total = sum(len(g['kw']) for g in groups)
        avg = sum(g['cpc'] for g in groups) / len(groups)
        clicks = budget * 7 / avg
        week += budget * 7
        print('=' * 74)
        print('КАМПАНИЯ: AIT | %s' % cname)
        print('  бюджет %d руб/день (%d руб/нед) | групп %d | фраз %d | клик ~%.1f руб'
              % (budget, budget * 7, len(groups), kw_total, avg))
        print('  кликов в неделю: ~%d' % clicks)
        print('=' * 74)
        for g in groups:
            print('')
            print('--- группа: %s' % g['name'])
            print('    посадочная: %s%s' % (SITE, g['url']))
            print('    Заголовок 1 (%2d): %s' % (len(g['h1']), g['h1']))
